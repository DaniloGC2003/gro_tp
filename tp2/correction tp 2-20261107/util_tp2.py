class TreeNodePSE:
    """Cette classe permet de stoker un noeud de l'arbre d'exploration des solutions
    d'un pb de sac à dos"""
    __slots__ = ('parent', 'Fmax', 'Cstr', 'num_var', 'val_var') # thanks to Théophile P. ;-)
    def __init__ (self, parent, Fmax, Cstr, num_var, val_var):
        self.parent = parent     # référence vers le parent (None pour le sommet de l'arbre)
        self.Fmax = Fmax         # potentialité pour la fonction coût en ce noeud
        self.Cstr = Cstr         # ce qu'il reste à "manger" en contrainte (tableau numarray)
        self.num_var = num_var   # numéro de la variable pour laquelle ce noeud de l'arbre
                                 # donne une valeur (-1 pour le sommet)
        self.val_var = val_var   # valeur de x[num_var] (None pour le sommet)

    def __lt__(self, other):
        """ permet d'utiliser la file de priorité min (heappop, heappush) de python
        sans soucis..."""
        return self.Fmax > other.Fmax
        
    def __repr__(self):
        """affichage sommaire"""
        big_string = "< type TreeNodePSE"
        big_string += "\n  Fmax = "+format(self.Fmax)
        big_string += "\n  Cstr = "+format(self.Cstr)
        big_string += "\n  num_var = "+format(self.num_var)
        big_string += "\n  val_var = "+format(self.val_var)+"  >\n"      
        return big_string

reponses_usuelles = {1: "Modèle chargé (mais pas encore optimisé)",
                     2: "Optimum atteint",
                     3: "Problème non réalisable (domaine admissible vide)",
                     4: "Problème non réalisable ou Fct objectif non bornée",
                     5: "Fct objectif non bornée"}
def status_to_str(cle):
    if cle in reponses_usuelles:
        return reponses_usuelles[cle]
    else:
        return f"status (={cle}) voir : " \
               +"https://docs.gurobi.com/projects/optimizer/en/current/reference/numericcodes/statuscodes.html#secstatuscodes"
    
